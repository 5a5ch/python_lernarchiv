const navigation = document.getElementById("file-navigation");
const inputTitle = document.getElementById("input-title");
const inputFile = document.getElementById("input-file");
const inputQuestion = document.getElementById("input-question");
const inputForm = document.getElementById("input-form");
const pythonInput = document.getElementById("python-input");
const codeContent = document.getElementById("code-content");
const codeFile = document.getElementById("code-file");
const loadStatus = document.getElementById("load-status");
const outputContent = document.getElementById("output-content");
const runButton = document.getElementById("run-button");

let currentPythonCode = "";
let currentFileRunnable = false;
let hasRunCurrentFile = false;
let pyodideReadyPromise;
let resolvePythonInput;

const openingMessage = "Hier meine ersten Schritte in Python zu Aufgaben aus dem Lernfeld 5.\nDer Code wurde komplett ohne Hilfsmittel erarbeitet.\n\nFür die übersichtliche Darstellung hier war die KI so freundlich, mich zu unterstützen :-)";

function buildNavigation() {
    archive.forEach((category) => {
        const folder = document.createElement("details");
        folder.className = "nav-group";
        folder.open = archive.indexOf(category) === 0;

        const heading = document.createElement("summary");
        heading.textContent = category.name;
        folder.appendChild(heading);

        const files = document.createElement("div");
        files.className = "nav-files";

        category.files.forEach((file) => {
            const button = document.createElement("button");
            button.type = "button";
            button.className = "file-link";
            if (!file.runnable) button.classList.add("code-only");
            button.textContent = file.title;
            button.dataset.title = file.title;
            button.dataset.category = category.name;
            button.dataset.file = file.file;
            button.dataset.path = `${category.folder}/${file.file}`;
            button.dataset.runnable = String(file.runnable);
            button.addEventListener("click", () => loadPythonFile(button));
            files.appendChild(button);
        });

        folder.appendChild(files);
        navigation.appendChild(folder);
    });
}

function getPythonFileUrl(relativePath) {
    if (window.location.hostname.endsWith("github.io")) {
        const repositoryName = window.location.pathname.split("/").filter(Boolean)[0];
        const userName = window.location.hostname.split(".")[0];
        return `https://raw.githubusercontent.com/${userName}/${repositoryName}/main/${relativePath}`;
    }

    return `../${relativePath}`;
}

function updateRunButton() {
    runButton.disabled = !currentFileRunnable || currentPythonCode.length === 0;
  runButton.textContent = hasRunCurrentFile ? "Erneut ausführen" : "Ausführen";
}

function preparePythonCode(source) {
  const transformedSource = source.replace(/\binput\s*\(/g, "await __input(");
  const indentedSource = transformedSource.split("\n").map((line) => `    ${line}`).join("\n");
  return `import io\nimport traceback\nfrom contextlib import redirect_stdout, redirect_stderr\n\n__output = io.StringIO()\n\nasync def __input(prompt):\n    return await __input_from_js(prompt, __output.getvalue())\n\nasync def __run_user_code():\n${indentedSource}\n\nwith redirect_stdout(__output), redirect_stderr(__output):\n    try:\n        await __run_user_code()\n    except Exception:\n        traceback.print_exc(file=__output)\n__output.getvalue()`;
}

function showPythonQuestion(prompt, partialOutput) {
  outputContent.textContent = partialOutput ? String(partialOutput) : "";
    outputContent.scrollTop = 0;
    inputQuestion.textContent = prompt || "Eingabe erforderlich";
    inputForm.hidden = false;
    pythonInput.value = "";
    pythonInput.focus();
    return new Promise((resolve) => {
        resolvePythonInput = resolve;
    });
}

function finishPythonQuestion(event) {
  event.preventDefault();
  if (!resolvePythonInput) return;
  const answer = pythonInput.value;
  resolvePythonInput(answer);
  resolvePythonInput = null;
  inputForm.hidden = true;
  inputQuestion.textContent = "Eingabe übernommen.";
}

async function initializePython() {
    try {
        const pyodide = await loadPyodide();
        pyodide.globals.set("__input_from_js", showPythonQuestion);
        updateRunButton();
        return pyodide;
    } catch (error) {
        outputContent.textContent = `Python konnte nicht gestartet werden.\n\n${error}`;
        throw error;
    }
}

async function runCurrentPythonCode() {
    if (!currentFileRunnable) {
        outputContent.textContent = "Für diese Datei wird nur der Quellcode angezeigt. Die Ausführung im Browser ist nicht verfügbar.";
        return;
    }
    if (!currentPythonCode) return;

    runButton.disabled = true;
    hasRunCurrentFile = true;
    runButton.textContent = "Erneut ausführen";
    outputContent.textContent = "Programm wird ausgeführt ...";
    outputContent.scrollTop = 0;
    try {
        const pyodide = await pyodideReadyPromise;
      const collectedOutput = await pyodide.runPythonAsync(preparePythonCode(currentPythonCode));
      outputContent.textContent = collectedOutput || "Das Programm wurde ohne Ausgabe beendet.";
      outputContent.scrollTop = 0;
    } catch (error) {
      outputContent.textContent = `Python-Fehler:\n${error}`;
      outputContent.scrollTop = 0;
    } finally {
        updateRunButton();
    }
}

async function loadPythonFile(button) {
    document.querySelectorAll(".file-link").forEach((link) => link.classList.remove("active"));
    button.classList.add("active");

    inputTitle.textContent = button.dataset.title;
    inputFile.textContent = `${button.dataset.category} / ${button.dataset.file}`;
    currentFileRunnable = button.dataset.runnable === "true";
    hasRunCurrentFile = false;
    inputQuestion.textContent = currentFileRunnable ? "Das Programm wird vorbereitet ..." : "Für diese Datei ist keine Eingabe im Browser vorgesehen.";
    inputForm.hidden = true;
    codeFile.textContent = button.dataset.file;
    codeFile.title = button.dataset.file;
    currentPythonCode = "";
    codeContent.textContent = "Python-Datei wird geladen ...";
    document.querySelector(".code-view").scrollTop = 0;
    outputContent.textContent = "";
    outputContent.scrollTop = 0;
    loadStatus.textContent = "Wird geladen ...";
    updateRunButton();

    try {
        const response = await fetch(getPythonFileUrl(button.dataset.path));
        if (!response.ok) throw new Error(`HTTP ${response.status}`);
        currentPythonCode = await response.text();
        codeContent.textContent = currentPythonCode;
        loadStatus.textContent = "Datei geladen";
        if (!/\binput\s*\(/.test(currentPythonCode)) {
          inputQuestion.textContent = "Keine Eingabe nötig";
        }
        updateRunButton();

        if (!currentFileRunnable) {
          outputContent.textContent = "CODE only";
          outputContent.scrollTop = 0;
        }
    } catch (error) {
        codeContent.textContent = `Die Python-Datei konnte nicht geladen werden.\n\nGeprüfter Pfad: ${button.dataset.path}\nFehler: ${error.message}`;
        loadStatus.textContent = "Ladefehler";
        outputContent.textContent = "Die Datei konnte nicht ausgeführt werden.";
        console.error(error);
    }
}

runButton.addEventListener("click", runCurrentPythonCode);
inputForm.addEventListener("submit", finishPythonQuestion);
buildNavigation();
pyodideReadyPromise = initializePython();

inputTitle.textContent = "Willkommen im Python-Lernarchiv";
inputQuestion.textContent = "Wähle links eine Python-Datei aus.";
codeContent.textContent = openingMessage;

console.log("Python-Lernarchiv gestartet");
